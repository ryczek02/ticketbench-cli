package report

import (
	"fmt"
	"math"
	"slices"
	"strings"
)

// writeValues emits generated/values.tex: every aggregated number keyed by
// its coordinates, so the prose of the report can cite measurements without
// copying them by hand.
//
//	\val{postgres}{10000000}{off}{R4}        mean server time [ms]
//	\valp{postgres}{10000000}{off}{R4}       same, plain number (for arithmetic)
//	\cval{valkey}{1000000}{lua}{1000}        contention throughput [bookings/s]
//	\cpn{valkey}{1000000}{lua}{1000}         contention p95 [ms]
//	\lval{mongo}{10000000}{load}             load / index build time [s]
//	\sval{valkey}{10000000}{on}              storage [MB]
//	\ratio{postgres}{mariadb}{10000000}{off}{R4}  ratio of two mean times
func (r *Report) writeValues(o *out) error {
	var b strings.Builder
	b.WriteString("% generated by tbench report\n\\makeatletter\n")
	def := func(key string, v float64) {
		if math.IsNaN(v) || math.IsInf(v, 0) {
			return
		}
		fmt.Fprintf(&b, "\\@namedef{tb@%s}{%s}\n", key, strings.TrimRight(strings.TrimRight(fmt.Sprintf("%.4f", v), "0"), "."))
	}
	sc := r.Scenarios()
	keys := make([]ScenarioKey, 0, len(sc))
	for k := range sc {
		keys = append(keys, k)
	}
	slices.SortFunc(keys, func(a, b ScenarioKey) int { return strings.Compare(fmt.Sprint(a), fmt.Sprint(b)) })
	for _, k := range keys {
		if v := sc[k]; v.Server.N > 0 {
			def(fmt.Sprintf("s@%s@%d@%s@%s", k.Store, k.Tickets, onOff(k.Indexes), k.Scenario), v.Server.Mean)
		}
	}
	c := r.Contention()
	ckeys := make([]ContentionKey, 0, len(c))
	for k := range c {
		ckeys = append(ckeys, k)
	}
	slices.SortFunc(ckeys, func(a, b ContentionKey) int { return strings.Compare(fmt.Sprint(a), fmt.Sprint(b)) })
	for _, k := range ckeys {
		v := c[k]
		def(fmt.Sprintf("c@%s@%d@%s@%d", k.Store, k.Tickets, k.Strategy, k.Clients), v.Throughput.Mean)
		def(fmt.Sprintf("p@%s@%d@%s@%d", k.Store, k.Tickets, k.Strategy, k.Clients), v.P95.Mean)
		def(fmt.Sprintf("k@%s@%d@%s@%d", k.Store, k.Tickets, k.Strategy, k.Clients), v.Conflicts.Mean)
	}
	type lk struct {
		tickets int64
		store   string
		kind    string
	}
	loads := map[lk][]float64{}
	for _, x := range r.loads {
		if isSecurity(x) {
			continue
		}
		k := lk{x.i("tickets"), x["store"], x["kind"]}
		loads[k] = append(loads[k], x.f("server_ms")/1000)
	}
	lkeys := make([]lk, 0, len(loads))
	for k := range loads {
		lkeys = append(lkeys, k)
	}
	slices.SortFunc(lkeys, func(a, b lk) int { return strings.Compare(fmt.Sprint(a), fmt.Sprint(b)) })
	for _, k := range lkeys {
		def(fmt.Sprintf("l@%s@%d@%s", k.store, k.tickets, k.kind), summarize(loads[k]).Mean)
	}
	for _, x := range r.stats {
		if isSecurity(x) {
			continue
		}
		def(fmt.Sprintf("m@%s@%d@%s", x["store"], x.i("tickets"), onOff(x.b("indexes"))), float64(x.i("total_bytes"))/(1<<20))
	}
	b.WriteString(`\makeatother
\newcommand{\tbget}[1]{\ifcsname tb@#1\endcsname\csname tb@#1\endcsname\else nan\fi}
\newcommand{\tbnum}[1]{\ifcsname tb@#1\endcsname\num[round-mode=figures,round-precision=3]{\csname tb@#1\endcsname}\else --\fi}
\newcommand{\val}[4]{\tbnum{s@#1@#2@#3@#4}}
\newcommand{\valp}[4]{\tbget{s@#1@#2@#3@#4}}
\newcommand{\cval}[4]{\tbnum{c@#1@#2@#3@#4}}
\newcommand{\cpn}[4]{\tbnum{p@#1@#2@#3@#4}}
\newcommand{\ckn}[4]{\tbnum{k@#1@#2@#3@#4}}
\newcommand{\lval}[3]{\tbnum{l@#1@#2@#3}}
\newcommand{\sval}[3]{\tbnum{m@#1@#2@#3}}
\newcommand{\ratio}[5]{\ifcsname tb@s@#1@#3@#4@#5\endcsname\ifcsname tb@s@#2@#3@#4@#5\endcsname\num[round-mode=figures,round-precision=2]{\fpeval{\csname tb@s@#1@#3@#4@#5\endcsname/\csname tb@s@#2@#3@#4@#5\endcsname}}\else --\fi\else --\fi}
\newcommand{\cratio}[6]{\ifcsname tb@c@#1@#3@#4@#6\endcsname\ifcsname tb@c@#2@#3@#5@#6\endcsname\num[round-mode=figures,round-precision=2]{\fpeval{\csname tb@c@#1@#3@#4@#6\endcsname/\csname tb@c@#2@#3@#5@#6\endcsname}}\else --\fi\else --\fi}
`)
	return o.text("values.tex", b.String())
}
